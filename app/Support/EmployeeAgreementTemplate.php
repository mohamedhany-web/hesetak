<?php

namespace App\Support;

/**
 * قالب عقد موظف افتراضي قابل للتعديل في نموذج الإدارة.
 */
final class EmployeeAgreementTemplate
{
    public static function contractTerms(): string
    {
        return <<<'TXT'
1) يلتزم الطرف الثاني (الموظف) بأداء المهام الموكلة إليه وفق المسمى الوظيفي والسياسات الداخلية لمنصة حصتك.
2) يخضع العقد لأحكام أنظمة العمل المعمول بها في المملكة العربية السعودية، بما في ذلك ساعات العمل والإجازات والسرية.
3) يُصرف الراتب الشهري المتفق عليه بالريال السعودي وفق سياسة الرواتب المعتمدة، بعد أي خصومات نظامية أو متفق عليها.
4) يلتزم الموظف بالمحافظة على سرية بيانات المنصة والطلاب وأولياء الأمور، وعدم إفشاء أي معلومات إلا بصلاحية رسمية.
5) يحق لأي من الطرفين إنهاء العقد وفق المدة النظامية أو باتفاق مكتوب، مع تسوية المستحقات حتى تاريخ الانتهاء.
6) أي تعديل جوهري على الأجر أو المهام أو المدة يُوثَّق بإصدار جديد من الاتفاقية وموافقة الطرفين.
TXT;
    }

    public static function agreementTerms(): string
    {
        return <<<'TXT'
البند (1): موضوع الاتفاقية — تنظيم علاقة عمل/تعاون تشغيلي بين منصة حصتك والموظف لأداء مهام وظيفية محددة.
البند (2): الطرف الأول — منصة حصتك (المشغّل)، والطرف الثاني — الموظف المذكور بياناته في صدر العقد.
البند (3): الأجر والمزايا — الراتب الأساسي الشهري المبيّن أعلاه، وأي بدلات تُضاف لاحقاً بملحق مكتوب.
البند (4): الالتزامات — الالتزام بتعليمات الإدارة، جودة الخدمة، المواعيد، وسياسات الأمن والخصوصية.
البند (5): التعارض والسلوك المهني — الامتناع عن أي نشاط يتعارض مع مصلحة المنصة أو يضر بسمعتها.
البند (6): حل النزاعات — يُسعى للتسوية الودية أولاً، ثم تُحال النزاعات للجهات المختصة وفق الأنظمة السعودية.
البند (7): النسخ والتوقيع — تُعد النسخة الإلكترونية الموقّعة (مع رمز التأكيد) نسخة أصلية سارية بين الطرفين.
TXT;
    }

    public static function defaultDescription(): string
    {
        return 'اتفاقية عمل تشغيلية بين منصة حصتك والموظف، تحدد الأجر والمدة والالتزامات المتبادلة.';
    }
}
